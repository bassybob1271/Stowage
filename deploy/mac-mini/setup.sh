#!/bin/bash
# Set up a Mac (the Bazzy Mac mini) to run Bazzy Live + BazzyBox behind the Cloudflare Tunnel,
# starting at login and restarting on crashes.
#
#   curl -fsSL https://raw.githubusercontent.com/bassybob1271/Stowage/main/deploy/mac-mini/setup.sh | bash
#   (or: bash deploy/mac-mini/setup.sh from a clone)
#
# Before running, copy the tunnel files from the old machine into ~/.cloudflared/:
#   ~/.cloudflared/cert.pem and ~/.cloudflared/<tunnel-id>.json
# Settings (.env, apps/live/.env, mounts.yaml) are copied over if you have them; otherwise
# make-env.sh creates them and asks for your Backblaze B2 keys.
# Without the tunnel files it signs in to Cloudflare and makes a new tunnel instead.
#
# Options (environment variables):
#   STOWAGE_DIR=~/Stowage      where the code lives
#   TUNNEL_NAME=bazzy          tunnel to reuse or create
#   LIVE_HOST=live.bazzy.io    BOX_HOST=box.bazzy.io
#   TV_HOST=bazzyvideo.com TV_PORT=80   also route Bazzy TV, when it runs on this Mac
set -euo pipefail

DIR=${STOWAGE_DIR:-$HOME/Stowage}
TUNNEL=${TUNNEL_NAME:-bazzy}
LIVE_HOST=${LIVE_HOST:-live.bazzy.io}
BOX_HOST=${BOX_HOST:-box.bazzy.io}
TV_HOST=${TV_HOST:-}
TV_PORT=${TV_PORT:-80}
LABEL=io.bazzy.stack
say() { printf '\n\033[1;31m▸\033[0m %s\n' "$*"; }

[ "$(uname)" = Darwin ] || { echo "This script is for macOS."; exit 1; }

say "Tools (Homebrew, Node 22, pnpm, git)"
if ! command -v brew >/dev/null; then
  /bin/bash -c "$(curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh)"
  eval "$(/opt/homebrew/bin/brew shellenv 2>/dev/null || /usr/local/bin/brew shellenv)"
fi
brew list node@22 >/dev/null 2>&1 || brew install node@22
export PATH="$(brew --prefix node@22)/bin:$PATH"
command -v git >/dev/null || brew install git
corepack enable >/dev/null 2>&1 || npm i -g pnpm
# The FFmpeg build is Intel-only; Apple Silicon runs it through Rosetta (VideoToolbox still works).
if [ "$(uname -m)" = arm64 ] && ! /usr/bin/pgrep -q oahd; then
  softwareupdate --install-rosetta --agree-to-license
fi

say "Code → $DIR"
if [ -d "$DIR/.git" ]; then
  git -C "$DIR" pull --ff-only
else
  git clone https://github.com/bassybob1271/Stowage.git "$DIR"
fi
cd "$DIR"

if [ ! -f .env ] || [ ! -f apps/live/.env ] || [ ! -f mounts.yaml ]; then
  say "Settings (no .env files yet: making new ones)"
  bash deploy/mac-mini/make-env.sh
fi
grep -q '^BAZZYBOX=true' .env || echo "  note: .env has no BAZZYBOX=true, so BazzyBox won't start"

say "Install and build"
pnpm install --frozen-lockfile
pnpm --filter @stowage/live fetch-bins
# "server..." also builds the shared + storage packages it imports.
pnpm --filter @stowage/web build
pnpm --filter "@stowage/server..." build

say "Cloudflare Tunnel '$TUNNEL'"
CF="$DIR/apps/live/bin/cloudflared"
mkdir -p "$HOME/.cloudflared" deploy/cloudflared
[ -f "$HOME/.cloudflared/cert.pem" ] || "$CF" tunnel login
ID=$("$CF" tunnel list -o json 2>/dev/null | /usr/bin/python3 -c "import json,sys;print(next((t['id'] for t in json.load(sys.stdin) if t['name']=='$TUNNEL'),''))")
if [ -z "$ID" ]; then
  "$CF" tunnel create "$TUNNEL"
  ID=$("$CF" tunnel list -o json | /usr/bin/python3 -c "import json,sys;print(next(t['id'] for t in json.load(sys.stdin) if t['name']=='$TUNNEL'))")
fi
CRED="$HOME/.cloudflared/$ID.json"
[ -f "$CRED" ] || { echo "  The tunnel exists but $CRED is missing. AirDrop it from the old Mac, then rerun."; exit 1; }
cp "$CRED" "deploy/cloudflared/$ID.json"
{
  echo "# Generated by deploy/mac-mini/setup.sh"
  echo "tunnel: $ID"
  echo "credentials-file: $DIR/deploy/cloudflared/$ID.json"
  echo "ingress:"
  echo "  - hostname: $LIVE_HOST"
  echo "    service: http://127.0.0.1:8790"
  echo "  - hostname: $BOX_HOST"
  echo "    service: http://127.0.0.1:8787"
  if [ -n "$TV_HOST" ]; then
    echo "  - hostname: $TV_HOST"
    echo "    service: http://127.0.0.1:$TV_PORT"
  fi
  echo "  - service: http_status:404"
} > deploy/cloudflared/native.yml
for h in "$LIVE_HOST" "$BOX_HOST" ${TV_HOST:+"$TV_HOST"}; do
  "$CF" tunnel route dns --overwrite-dns "$TUNNEL" "$h" || echo "  could not route $h (is its domain on this Cloudflare account?)"
done

say "Start at login (launchd: $LABEL)"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
mkdir -p "$HOME/Library/LaunchAgents" "$HOME/Library/Logs"
cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key><array><string>/bin/sh</string><string>$DIR/apps/live/scripts/run-native.sh</string></array>
  <key>EnvironmentVariables</key><dict><key>PATH</key><string>$(dirname "$(command -v node)"):/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin</string></dict>
  <key>WorkingDirectory</key><string>$DIR</string>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>StandardOutPath</key><string>$HOME/Library/Logs/bazzy.log</string>
  <key>StandardErrorPath</key><string>$HOME/Library/Logs/bazzy.log</string>
</dict></plist>
EOF
launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"

say "Checking"
for i in $(seq 1 30); do
  curl -fs -o /dev/null http://127.0.0.1:8790/healthz && break
  sleep 2
done
curl -fs http://127.0.0.1:8790/healthz && echo "  Bazzy Live is running" || echo "  Bazzy Live didn't answer yet: tail -f ~/Library/Logs/bazzy.log"
curl -fs -o /dev/null http://127.0.0.1:8787/api/health && echo "  BazzyBox is running" || echo "  BazzyBox didn't answer yet: tail -f ~/Library/Logs/bazzy.log"

cat <<EOF

Done. This Mac now serves https://$LIVE_HOST and https://$BOX_HOST${TV_HOST:+ and https://$TV_HOST}.
• Stop the tunnel on the old Mac, or Cloudflare splits visitors between both machines.
• Keep this Mac awake: System Settings → Energy → "Prevent automatic sleeping", and turn on
  "Start up automatically after a power failure". Turn on automatic login so it starts after a reboot.
• Logs: tail -f ~/Library/Logs/bazzy.log     Restart: launchctl kickstart -k gui/$(id -u)/$LABEL
• Update later: cd $DIR && git pull && bash deploy/mac-mini/setup.sh
EOF
