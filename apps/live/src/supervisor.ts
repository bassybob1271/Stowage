import { spawn, spawnSync, type ChildProcess } from 'node:child_process';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import type { Config } from './config.js';
import { buildLadder, ffmpegArgs, type Rung, type SourceInfo } from './ladder.js';
import { log } from './log.js';

export interface StreamState {
  name: string; // MediaMTX path, e.g. "live/show"
  slug: string; // URL-safe id used under /hls and /watch
  status: 'starting' | 'live' | 'restarting' | 'ended';
  startedAt: string;
  source?: SourceInfo;
  rungs: Rung[];
  encoder: string;
  restarts: number;
  readers: number;
}

const API = '127.0.0.1:9997';
const RTSP = '127.0.0.1:8554';

export const slugOf = (path: string) => path.replace(/[^a-zA-Z0-9_-]+/g, '-').replace(/^-+|-+$/g, '').toLowerCase();

function yamlStr(s: string) {
  return JSON.stringify(s); // JSON strings are valid YAML scalars
}

export interface MtxOptions {
  /** Local URL MediaMTX POSTs every publish/read request to (apps/live decides). */
  authUrl: string;
  /** Record each path to cfg.recordDir. */
  record: boolean;
}

/** MediaMTX config: ingest on LIVE_INGEST_HOST; every publish/read is checked by apps/live; read + API from localhost only. */
export function mediamtxConfig(cfg: Config, o: MtxOptions): string {
  const h = cfg.LIVE_INGEST_HOST;
  return `# Generated by apps/live — edits are overwritten on start.
logLevel: info
logDestinations: [stdout]
api: yes
apiAddress: ${API}
metrics: no
pprof: no
playback: no
hls: no
rtsp: yes
rtspTransports: [tcp]
rtspAddress: ${RTSP}
rtmp: yes
rtmpAddress: ${h}:${cfg.LIVE_RTMP_PORT}
srt: yes
srtAddress: ${h}:${cfg.LIVE_SRT_PORT}
webrtc: yes
webrtcAddress: ${h}:${cfg.LIVE_WHIP_PORT}
authMethod: http
authHTTPAddress: ${yamlStr(o.authUrl)}
authHTTPExclude:
  - action: api
pathDefaults:
  record: ${o.record ? 'yes' : 'no'}
  recordPath: ${yamlStr(join(cfg.recordDir, '%path', '%Y-%m-%d_%H-%M-%S-%f'))}
  recordFormat: fmp4
  recordSegmentDuration: ${cfg.LIVE_RECORD_SEGMENT}
  recordDeleteAfter: 0s
paths:
  all_others:
`;
}

export class Supervisor {
  private mtx?: ChildProcess;
  private readonly jobs = new Map<string, { proc?: ChildProcess; state: StreamState; stopping: boolean; backoff: number }>();
  private timer?: NodeJS.Timeout;
  private stopped = false;
  readonly encoder: 'videotoolbox' | 'x264';

  constructor(
    private readonly cfg: Config,
    private readonly mtxOptions: MtxOptions,
  ) {
    this.encoder = cfg.LIVE_ENCODER === 'auto' ? (this.hasVideotoolbox() ? 'videotoolbox' : 'x264') : cfg.LIVE_ENCODER === 'videotoolbox' ? 'videotoolbox' : 'x264';
  }

  private bin(name: string) {
    return join(this.cfg.binDir, name);
  }

  private hasVideotoolbox() {
    const r = spawnSync(this.bin('ffmpeg'), ['-hide_banner', '-v', 'error', '-f', 'lavfi', '-i', 'color=s=256x144:d=0.2', '-c:v', 'h264_videotoolbox', '-f', 'null', '-'], { timeout: 15_000 });
    return r.status === 0;
  }

  streams(): StreamState[] {
    return [...this.jobs.values()].map((j) => j.state).filter((s) => s.status !== 'ended');
  }

  /** MediaMTX paths that are publishing right now. */
  livePaths(): Set<string> {
    return new Set(this.streams().map((s) => s.name));
  }

  get(slug: string) {
    return [...this.jobs.values()].find((j) => j.state.slug === slug)?.state;
  }

  async start() {
    await mkdir(this.cfg.hlsDir, { recursive: true });
    if (this.mtxOptions.record) await mkdir(this.cfg.recordDir, { recursive: true });
    const cfgPath = join(this.cfg.LIVE_DATA_DIR, 'mediamtx.yml');
    await writeFile(cfgPath, mediamtxConfig(this.cfg, this.mtxOptions), { mode: 0o600 });
    // A crash of this process can orphan MediaMTX (holding the ingest ports): clear it first.
    const pidFile = join(this.cfg.LIVE_DATA_DIR, 'mediamtx.pid');
    const stale = Number(await readFile(pidFile, 'utf8').catch(() => ''));
    if (stale > 0) {
      const cmd = spawnSync('ps', ['-o', 'command=', '-p', String(stale)]).stdout?.toString() ?? '';
      if (cmd.includes(this.bin('mediamtx'))) {
        process.kill(stale, 'SIGTERM');
        await new Promise((r) => setTimeout(r, 500));
        log.warn('mediamtx.stale_killed', { pid: stale });
      }
    }
    // cwd = data dir: MediaMTX writes its auto-generated TLS key pair (auto.key/auto.crt) there, not in the repo.
    this.mtx = spawn(this.bin('mediamtx'), [resolve(cfgPath)], { stdio: ['ignore', 'pipe', 'pipe'], cwd: resolve(this.cfg.LIVE_DATA_DIR) });
    if (this.mtx.pid) await writeFile(pidFile, String(this.mtx.pid));
    const relay = (d: Buffer) => d.toString().split('\n').filter(Boolean).forEach((l) => log.debug('mediamtx', { line: l }));
    this.mtx.stdout!.on('data', relay);
    this.mtx.stderr!.on('data', relay);
    this.mtx.on('exit', (code) => {
      if (this.stopped) return;
      log.error('mediamtx.exited', { code });
      setTimeout(() => void this.start(), 2000); // keep ingest alive
    });
    log.info('mediamtx.started', {
      rtmp: `rtmp://${this.cfg.LIVE_INGEST_HOST}:${this.cfg.LIVE_RTMP_PORT}/live/<name>`,
      srt: `srt://${this.cfg.LIVE_INGEST_HOST}:${this.cfg.LIVE_SRT_PORT}`,
      whip: `http://${this.cfg.LIVE_INGEST_HOST}:${this.cfg.LIVE_WHIP_PORT}/live/<name>/whip`,
      encoder: this.encoder,
    });
    this.timer ??= setInterval(() => void this.poll().catch((e) => log.debug('poll.failed', { error: (e as Error).message })), 1500);
  }

  private async poll() {
    const res = await fetch(`http://${API}/v3/paths/list?itemsPerPage=500`);
    if (!res.ok) return;
    const body = (await res.json()) as { items: { name: string; ready: boolean; readers?: unknown[]; tracks?: string[] }[] };
    const ready = new Map(body.items.filter((p) => p.ready).map((p) => [p.name, p]));
    for (const [name, p] of ready) {
      const job = this.jobs.get(name);
      if (!job || job.state.status === 'ended') void this.begin(name);
      else job.state.readers = p.readers?.length ?? 0;
    }
    for (const [name, job] of this.jobs) if (!ready.has(name) && job.state.status !== 'ended') this.end(name);
  }

  private probe(name: string): Promise<SourceInfo> {
    return new Promise((resolve, reject) => {
      const p = spawn(this.bin('ffprobe'), ['-v', 'error', '-rtsp_transport', 'tcp', '-show_streams', '-of', 'json', `rtsp://${RTSP}/${name}`], { timeout: 15_000 });
      let out = '';
      p.stdout.on('data', (d) => (out += d));
      p.on('error', reject);
      p.on('close', (code) => {
        if (code !== 0) return reject(new Error(`ffprobe exited ${code}`));
        const streams = (JSON.parse(out).streams ?? []) as { codec_type: string; width?: number; height?: number; avg_frame_rate?: string; r_frame_rate?: string }[];
        const v = streams.find((s) => s.codec_type === 'video');
        const rate = (r?: string) => {
          const [a, b] = (r ?? '').split('/').map(Number);
          return a && b ? a / b : 0;
        };
        resolve({
          hasVideo: Boolean(v),
          hasAudio: streams.some((s) => s.codec_type === 'audio'),
          width: v?.width ?? 0,
          height: v?.height ?? 0,
          fps: rate(v?.avg_frame_rate) || rate(v?.r_frame_rate) || 30,
        });
      });
    });
  }

  private async begin(name: string) {
    const slug = slugOf(name);
    const existing = this.jobs.get(name);
    const state: StreamState = existing?.state.status === 'restarting' ? existing.state : {
      name, slug, status: 'starting', startedAt: new Date().toISOString(), rungs: [], encoder: this.encoder, restarts: 0, readers: 0,
    };
    const job = existing && existing.state.status !== 'ended' ? existing : { state, stopping: false, backoff: 1000 };
    job.state = state;
    job.stopping = false;
    this.jobs.set(name, job);

    let src: SourceInfo;
    try {
      src = await this.probe(name);
    } catch (e) {
      log.warn('stream.probe_failed', { name, error: (e as Error).message });
      return this.scheduleRestart(name);
    }
    if (job.stopping) return;
    const outDir = join(this.cfg.hlsDir, slug);
    await rm(outDir, { recursive: true, force: true });
    const rungs = src.hasVideo ? buildLadder(this.cfg.ladder, src) : [{ name: 'audio', height: 0, width: 0, videoKbps: 0, audioKbps: 160 }];
    for (const r of rungs) await mkdir(join(outDir, r.name), { recursive: true });
    const plan = ffmpegArgs({
      input: `rtsp://${RTSP}/${name}`,
      outDir,
      rungs,
      src,
      encoder: this.encoder,
      segmentSec: this.cfg.LIVE_SEGMENT_SEC,
      playlistSegments: this.cfg.LIVE_PLAYLIST_SEGMENTS,
    });
    state.source = src;
    state.rungs = plan.rungs;
    const proc = spawn(this.bin('ffmpeg'), plan.args, { stdio: ['ignore', 'ignore', 'pipe'] });
    job.proc = proc;
    let tail = '';
    proc.stderr!.on('data', (d: Buffer) => (tail = (tail + d.toString()).slice(-2000)));
    proc.on('exit', (code, sig) => {
      if (job.stopping) return;
      log.warn('ffmpeg.exited', { name, code, sig, tail: tail.trim().split('\n').slice(-3).join(' | ') });
      this.scheduleRestart(name);
    });
    // Live once the master playlist and first segments exist.
    const t0 = Date.now();
    const check = setInterval(async () => {
      if (job.stopping || job.proc !== proc) return clearInterval(check);
      const { existsSync } = await import('node:fs');
      if (existsSync(join(outDir, 'master.m3u8')) && existsSync(join(outDir, rungs[rungs.length - 1]!.name, 'index.m3u8'))) {
        clearInterval(check);
        state.status = 'live';
        job.backoff = 1000;
        log.info('stream.live', { name, rungs: rungs.map((r) => r.name), encoder: this.encoder, ms: Date.now() - t0 });
      }
    }, 300);
    log.info('stream.starting', { name, source: `${src.width}x${src.height}@${src.fps.toFixed(2)}`, audio: src.hasAudio, rungs: rungs.map((r) => `${r.name}:${r.videoKbps}k`) });
  }

  private scheduleRestart(name: string) {
    const job = this.jobs.get(name);
    if (!job || job.stopping) return;
    job.state.status = 'restarting';
    job.state.restarts++;
    const delay = job.backoff;
    job.backoff = Math.min(30_000, job.backoff * 2);
    setTimeout(() => {
      if (!job.stopping && job.state.status === 'restarting') void this.begin(name);
    }, delay);
  }

  private end(name: string) {
    const job = this.jobs.get(name);
    if (!job) return;
    job.stopping = true;
    job.proc?.kill('SIGINT'); // lets FFmpeg finish the last segment
    job.state.status = 'ended';
    log.info('stream.ended', { name });
  }

  async stop() {
    this.stopped = true;
    if (this.timer) clearInterval(this.timer);
    for (const name of this.jobs.keys()) this.end(name);
    const mtx = this.mtx;
    if (mtx && mtx.exitCode === null) {
      const exited = new Promise((r) => mtx.once('exit', r));
      mtx.kill('SIGTERM');
      await Promise.race([exited, new Promise((r) => setTimeout(r, 3000))]);
      if (mtx.exitCode === null) mtx.kill('SIGKILL');
    }
  }
}
